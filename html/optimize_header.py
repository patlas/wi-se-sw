#!/usr/bin/env python3
"""Recompress the generated, gzip-encoded terminal without changing its contents."""
import gzip
from pathlib import Path
import re

import zopfli.gzip

header = Path(__file__).resolve().parent.parent / 'include' / 'html.h'
text = header.read_text(encoding='utf-8')
original = bytes(int(value, 16) for value in re.findall(r'0x([0-9a-fA-F]{2})', text))
html = gzip.decompress(original)
compressed = zopfli.gzip.compress(html, numiterations=20)
if gzip.decompress(compressed) != html:
    raise ValueError('Compressed HTML does not match its source')
if len(compressed) >= len(original):
    print(f'Existing HTML is already smaller ({len(original)} bytes); unchanged.')
else:
    lines = []
    for offset in range(0, len(compressed), 19):
        chunk = compressed[offset:offset + 19]
        suffix = ',' if offset + 19 < len(compressed) else ''
        lines.append('  ' + ', '.join(f'0x{value:02x}' for value in chunk) + suffix)
    header.write_text(
        '// #### This file is automatically generated #### \n'
        '// Source: html/dist/index.html; gzip optimized by html/optimize_header.py\n\n'
        f'unsigned int index_html_len = {len(compressed)};\n'
        f'unsigned int index_html_size = {len(html)};\n\n'
        'const uint8_t index_html[] PROGMEM = {\n' + '\n'.join(lines) + '\n};\n',
        encoding='utf-8',
    )
    print(f'Compressed HTML: {len(original)} -> {len(compressed)} bytes.')
